/**
 * 作品検索の突き合わせ用に文字列をならす。
 *
 * ★ ビルド時（WorkTable が各行に焼き込む）と実行時（読者が打った文字列）の
 *   **両方**がこの関数を呼ぶ。片方だけ変えると検索が当たらなくなるので、
 *   ならし方を変えるときは必ずここだけを直すこと。
 *
 *   normalize('NFKC')  全角英数→半角、半角カナ→全角。
 *                      「ＴＥＮＥＴ」を「TENET」で、「ﾅﾆ」を「ナニ」で引ける
 *   toLowerCase()      大文字小文字を無視する
 *   空白を落とす        全角/半角スペースの違いで外さないようにする
 *   中黒を落とす        「スター・ウォーズ」を「スターウォーズ」でも引ける
 *
 * ★ ひらがな↔カタカナは畳んでいない。
 *   畳むと「はな」で意図しない作品まで当たるようになり、
 *   件数が増えるほど読者が目的の行を見つけにくくなるため。
 */
export function normalizeForSearch(value: string): string {
  return (
    value
      .normalize('NFKC')
      .toLowerCase()
      // NFKC で U+3000 は半角スペースになるが、念のため両方落とす
      .replace(/[\s　]+/g, '')
      // 中黒（全角・半角カナ用・その他の中点）
      .replace(/[・･·‧]/g, '')
  )
}
