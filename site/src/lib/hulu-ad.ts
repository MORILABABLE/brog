/**
 * Hulu（afb）の広告を出すかどうかと、出すなら何を出すかを決める1か所。
 *
 * ■ この広告の設計は U-NEXT と根本的に違う。**作品を訴求しない**
 *
 * Hulu の掲載ガイドライン１）はこうなっている。
 *
 *   > 使用可能タイトルについては配信中の作品のみで御座います。
 *   > TBS作品、ディズニー作品、配信終了タイトルは掲載NGとなります。
 *   > ※訴求自体がNGとなります。
 *
 * 「配信中」＝**Hulu で配信中**。ところが当サイトは
 * **Hulu の配信状況を知る手段を持っていない**（利用規約が自動アクセスを禁止。
 * docs/SOURCES-UNEXT-HULU.md の結論）。つまり
 * **「この作品はHuluで配信中だ」と言える作品が1本も無い。**
 *
 * だから作品単位の Hulu 訴求は構造的に不可能で、
 * **サイト内の Hulu 検索リンク（824本）をafbリンクに差し替えることはできない。**
 * 差し替えれば全部が「配信中か分からないタイトルの訴求」になり、
 * 却下条件の「未配信タイトルでの訴求 → 提携解除・成果全却下」に当たる。
 *
 * ここが出すのは**サービスの入口1本だけ**。文言に作品名を入れない。
 * 作品を訴求していなければ、配信中かどうかの判定がそもそも要らない。
 *
 *   読者のための検索リンク（作品名つき・成果にならない）  … search-links.ts
 *   成果になる導線（作品名なし・LPへ）                    … このファイル
 *
 * ■ ガイドラインのうち、コードで守れるもの
 *   １）掲載NG（TBS作品・ディズニー作品） … `hulu-ng.ts` と下の BLOCKED_SERVICES
 *   １）配信終了タイトル                   … 作品名を持たない（上のとおり）
 *   ３）画像の流用禁止                     … Hulu の素材を1枚も使っていない
 *   ４）PR表記                             … **ページ冒頭の `AffiliateNotice`**（枠の中には置かない。下の★）
 *
 * ■ コードでは守れないもの（人が守る）
 *   リスティング制限 … 社名・商標・作品名での広告出稿をしない（出稿していない）
 *   ディスプレイ広告 … Hulu直リンク・酷似LP・誤認クリエイティブを作らない
 *   掲載NGジャンル   … アダルト・ギャンブルを扱わない
 *
 * ■ 未設定なら1バイトも出ない
 * `PUBLIC_AFB_HULU_LP` が空のあいだ `huluAd()` は必ず null を返す。
 */
import { huluNgHitsIn } from './hulu-ng'
import { SLOT_OK, withSlot, type AfbSlot } from './afb'

/**
 * 🔴 **LP・1x1・バナーの3つは「同じ原稿」から取ること。**
 *
 * afb は原稿（バナー／テキスト）ごとに `a=` が違う。実物:
 *
 *   テキスト原稿  a=G8792C-T298408v   1x1: /lead/G8792C/U9922286/T298408v
 *   バナー原稿    a=G8792C-q298067J   1x1: /lead/G8792C/U9922286/q298067J
 *
 * **片方の href に、もう片方の画像や1x1を組み合わせてはいけない。**
 * リンクは動いてしまうので画面では気づけず、**成果が別の原稿に付く**か、
 * 計測が合わなくなる。`.env` を触るときは3行まとめて差し替える。
 */

/**
 * LP。**afb 管理画面から取ったリンクコードの href をそのまま貼る。**
 * `a=` と `p=` は afb が発行する値なので、**手で組み立てないこと**。
 */
const LP = import.meta.env.PUBLIC_AFB_HULU_LP ?? ''

/**
 * 表示回数の計測用の 1x1 画像（原稿に付いてくるもの）。
 *
 * ★ **リンクコードの一部**なので、付いてきたら一緒に出す。
 *   afb が認めている改変は rel / target / パラメータ追加までで、
 *   原稿から要素を落とすことは含まれていない（docs/AFFILIATE.md 11-3）。
 * ★ 無くてもリンクは動く。未設定なら出さない。
 */
const IMPRESSION = import.meta.env.PUBLIC_AFB_HULU_IMP ?? ''

/**
 * バナー原稿の画像。**入っていればバナー、空ならテキストリンクになる。**
 *
 * ■ なぜバナーがガイドライン上むしろ安全か
 * ３）「Hulu本体から画像コンテンツを流用する事は禁止しており、
 * **管理画面に反映されている画像コンテンツのみ使用可**」。
 * この画像は afb の管理画面が配っているもの（`www.afi-b.com/upload_image/…`）で、
 * **Hulu 本体から取ってきたものではない。** そこが要件そのもの。
 *
 * 🔴 **画像を自前のドメインに再ホストしないこと。** 落とした瞬間に
 *   「管理画面に反映されている画像」ではなくなるうえ、差し替えにも追随できない。
 *   当サイトは作品ポスターを再ホストしているが（許諾済み）、**これは別物。**
 */
const BANNER = import.meta.env.PUBLIC_AFB_HULU_BANNER ?? ''

/**
 * バナーの寸法（`320x50` の形）。**原稿に書いてある値をそのまま。**
 * 読めない書き方なら既定に落ちる。狭い画面での縮小は
 * global.css の `img { max-width: 100%; height: auto }` が面倒を見る。
 */
const BANNER_SIZE = import.meta.env.PUBLIC_AFB_HULU_BANNER_SIZE ?? '320x50'

function bannerSize(): { width: number; height: number } {
  const m = /^(\d{1,4})x(\d{1,4})$/.exec(BANNER_SIZE.trim())
  return m ? { width: Number(m[1]), height: Number(m[2]) } : { width: 320, height: 50 }
}

/** Hulu の広告を出せる状態か。**LPが唯一の必須。** */
export const HULU_AD_ENABLED = Boolean(LP)

/**
 * リンクの文字。**afb のテキスト原稿の文言そのまま。**
 * **バナーが設定されているときは使わない**（原稿を混ぜないため）。
 *
 * ★ **書き換えないこと。** 広告主が用意した表現で、
 *   当サイトが作った「見放題」の主張ではない、という切り分けがここで効く。
 * ★ **この枠に当サイトの地の文は無い**（下の★）。足すなら作品にも配信状況にも触れないこと。
 */
const ACTION = 'Huluなら人気の映画、ドラマ、アニメ、バラエティが見放題！'

/**
 * バナーの代替テキスト。**原稿の `alt="hulu"` そのまま。**
 *
 * ★ 説明を足したくなるが、足さないこと。リンクの中の唯一のテキストなので、
 *   ここに書いた言葉は**当サイトが書いた広告文**になる。
 *   作品にも配信状況にも触れない1語のままにしておく。
 */
const BANNER_ALT = 'hulu'

/**
 * ★ **この枠は文字を持たない**（2026-09-14・運用者の指定で撤去）。
 *
 * 以前は「Huluは月額制の…」という説明文と、
 * 「当サイトはHuluの配信状況を扱っていません…」という注意書きを出していた。
 * どちらも**ガイドラインが求めているものではない**ので外した。
 *
 * | 撤去したもの | 要件はどこが満たしているか |
 * |---|---|
 * | 枠の中の「PR」バッジ | **ページ冒頭の `AffiliateNotice`**（「[PR] このページにはアフィリエイト広告…」）。ステマ規制が求めるのは「一般消費者にとって事業者の表示であることが明瞭」で、**位置は冒頭がむしろ要件**（docs/AFFILIATE.md 5-5）。記事・作品ページの両方に出ている |
 * | 「当サイトはHuluの配信状況を扱っていません」 | Hulu のガイドラインに**記載必須の注意文言は無い**（U-NEXT の注意事項【4】とはここが違う）。同じ内容は「他のサービスで探す」の節が既に書いている（「当サイトは…5サービスの配信状況を把握できます」） |
 * | 「Huluは月額制の…」の説明文 | 当サイトが書く必要が無い。**バナーは広告主が作った絵**で、当サイトの主張を足さないほうが切り分けが明確になる |
 *
 * 🔴 **ただし「作品名を出さない」は変わらない。** 文字を足したくなったときは
 *   13-1 を読み直すこと。当サイトは Hulu の配信状況を持っていないので、
 *   作品に触れた瞬間に「未配信タイトルでの訴求」になりうる。
 *
 * ★ **文字を戻すなら、判断はこのファイルに置くこと。** コンポーネントに直接
 *   書かないこと（ガイドラインを1か所で確かめられなくなる）。
 */

/**
 * このサービスを扱っているページには出さない。
 *
 * ■ なぜ文字列照合ではないのか
 * 「ディズニー作品」を文字で当てようとすると、**サービス名の `Disney+` に
 * 全部当たる**（記事の表に265か所ある）。ほぼ全ページで広告が消えてしまう。
 * ページが Disney+ を扱っているかどうかは**メタデータで分かる**ので、
 * そちらで止める（誤検知ゼロ）。
 *
 * ★ Disney+ の在庫を「ディズニー作品の一覧」として使ってはいけない。
 *   2026-09-14 の実測で、Disney+ 日本の167件には名探偵コナン・
 *   ミッション:インポッシブル・天気の子が入っていた。
 *   **「Disney+で配信」と「ディズニー作品」は別物。**
 *   ただし**ページ単位で止めるぶんには安全側**なので、ここでは使う。
 */
const BLOCKED_SERVICES = ['disney-plus', 'disney+', 'disneyplus']

function blocksService(s: string): boolean {
  return BLOCKED_SERVICES.includes(s.trim().toLowerCase())
}

export interface HuluAd {
  href: string
  slot: AfbSlot
  /**
   * バナー原稿。**あるときはこれを出す**（テキストの `action` は使わない）。
   * 原稿を混ぜないために、どちらか一方しか描かない。
   */
  banner?: { src: string; alt: string; width: number; height: number }
  /** テキスト原稿の文言。**バナーが無いときだけ使う** */
  action: string
  /** 表示計測の1x1画像。未設定なら undefined */
  impression?: string
}

export interface HuluAdInput {
  slot: AfbSlot
  /**
   * そのページに出ている文字列（記事本文・作品名を並べたもの）。
   *
   * ★ **必ず渡すこと。** TBS作品・ディズニー作品が含まれていたら広告を出さない。
   *   渡さないと素通りする。
   */
  pageText?: string
  /**
   * そのページが扱っているサービス。記事なら `tags`、作品ページなら
   * `w.services` のキー。**Disney+ を含むページには出さない。**
   */
  services?: readonly string[]
}

/**
 * この場所に Hulu の広告を出すか。**出さないときは null。**
 *
 * 出さない条件は4つ。
 *   1. リンクコードが未設定（提携前＝既定の状態）
 *   2. 枠名が afb の使える文字でない（実装ミス。静かに壊れるより出さない）
 *   3. Disney+ を扱っているページ
 *   4. 掲載NG（TBS作品・ディズニー作品）がページにある
 */
export function huluAd(input: HuluAdInput): HuluAd | null {
  if (!HULU_AD_ENABLED) return null
  if (!SLOT_OK.test(input.slot)) return null
  if ((input.services ?? []).some(blocksService)) return null
  if (input.pageText && huluNgHitsIn(input.pageText).length > 0) return null

  return {
    href: withSlot(LP, input.slot),
    slot: input.slot,
    banner: BANNER ? { src: BANNER, alt: BANNER_ALT, ...bannerSize() } : undefined,
    action: ACTION,
    impression: IMPRESSION || undefined,
  }
}
